package com.example.bsa.service

import android.content.Context
import android.content.Intent
import android.net.Uri
import android.os.Build
import android.provider.Settings
import androidx.core.content.FileProvider
import com.example.BuildConfig
import kotlinx.coroutines.Dispatchers
import kotlinx.coroutines.withContext
import org.json.JSONObject
import java.io.File
import java.io.FileOutputStream
import java.net.HttpURLConnection
import java.net.URL
import java.security.MessageDigest

data class AppReleaseInfo(
    val versionCode: Int,
    val versionName: String,
    val apkFileName: String,
    val apkUrl: String,
    val sha256: String,
    val fileSizeBytes: Long,
    val releaseNotes: String,
    val publishedAtUtc: String
)

sealed interface UpdateCheckOutcome {
    data object NotConfigured : UpdateCheckOutcome
    data class UpToDate(val currentVersionName: String, val currentVersionCode: Int) : UpdateCheckOutcome
    data class UpdateAvailable(val release: AppReleaseInfo) : UpdateCheckOutcome
    data class Error(val message: String) : UpdateCheckOutcome
}

/**
 * 100% In-App Auto-Updater Service for BSA-YourView:
 * - Queries `update-manifest.json` (generated by ci_injector.py & build-apk.yml) or falls back
 *   to the GitHub Releases API for the configured repository.
 * - Downloads the APK inside the app with real-time progress callbacks (never opens Chrome/browser).
 * - Verifies SHA-256 checksum when present before launching Android's native in-app package installer
 *   via FileProvider (`application/vnd.android.package-archive`).
 */
class InAppUpdaterService(
    private val httpFetcher: HttpTextFetcher = DefaultHttpTextFetcher
) {

    fun resolveEffectiveRepo(repoOverride: String): String {
        return repoOverride.trim()
            .removePrefix("https://github.com/")
            .removePrefix("http://github.com/")
            .trim('/')
            .ifBlank { BuildConfig.GITHUB_UPDATE_REPO.trim() }
    }

    fun resolveManifestUrl(repoOverride: String): String {
        val repo = resolveEffectiveRepo(repoOverride)
        if (repo.contains("/")) {
            return "https://github.com/$repo/releases/latest/download/update-manifest.json"
        }
        return BuildConfig.UPDATE_MANIFEST_URL.trim()
    }

    suspend fun checkForUpdate(
        repoOverride: String,
        currentVersionCode: Int = BuildConfig.VERSION_CODE,
        currentVersionName: String = BuildConfig.VERSION_NAME
    ): UpdateCheckOutcome = withContext(Dispatchers.IO) {
        val repo = resolveEffectiveRepo(repoOverride)
        val manifestUrl = resolveManifestUrl(repoOverride)
        if (manifestUrl.isBlank() && repo.isBlank()) {
            return@withContext UpdateCheckOutcome.NotConfigured
        }

        // 1. Primary path: ci_injector.py generated update-manifest.json
        val manifestRelease = if (manifestUrl.isNotBlank()) {
            httpFetcher.get(manifestUrl)?.let { parseManifestJson(it) }
        } else null

        // 2. Fallback path: GitHub Releases API latest release
        val release = manifestRelease ?: if (repo.contains("/")) {
            httpFetcher.get("https://api.github.com/repos/$repo/releases/latest")
                ?.let { parseGitHubReleaseApiJson(it) }
        } else null

        if (release == null) {
            return@withContext UpdateCheckOutcome.Error(
                "Could not reach release manifest for ${repo.ifBlank { manifestUrl }}. Ensure a GitHub Release has been published."
            )
        }

        val isNewer = isNewerVersion(
            remoteCode = release.versionCode,
            remoteName = release.versionName,
            localCode = currentVersionCode,
            localName = currentVersionName
        )

        if (isNewer) {
            UpdateCheckOutcome.UpdateAvailable(release)
        } else {
            UpdateCheckOutcome.UpToDate(currentVersionName, currentVersionCode)
        }
    }

    /**
     * Streams the APK directly into app cache (`cacheDir/updates/`) with real-time progress and
     * SHA-256 verification — zero browser redirects.
     */
    suspend fun downloadApkInApp(
        context: Context,
        release: AppReleaseInfo,
        onProgress: (fraction: Float, downloadedBytes: Long, totalBytes: Long) -> Unit
    ): File = withContext(Dispatchers.IO) {
        val updatesDir = File(context.cacheDir, "updates").apply { mkdirs() }
        // Clean stale APKs before downloading fresh build
        updatesDir.listFiles()?.forEach { if (it.isFile) it.delete() }

        val safeName = release.apkFileName.replace(Regex("""[^A-Za-z0-9._-]"""), "_")
            .ifBlank { "BSA-YourView-v${release.versionName}.apk" }
        val targetFile = File(updatesDir, safeName)

        var currentUrl = release.apkUrl
        var redirects = 0
        var conn: HttpURLConnection? = null

        try {
            while (redirects < 6) {
                conn = (URL(currentUrl).openConnection() as HttpURLConnection).apply {
                    requestMethod = "GET"
                    instanceFollowRedirects = true
                    connectTimeout = 10_000
                    readTimeout = 30_000
                    setRequestProperty("User-Agent", "BSA-YourView-Updater/${BuildConfig.VERSION_NAME}")
                }
                val code = conn.responseCode
                if (code in 300..399) {
                    val location = conn.getHeaderField("Location")
                        ?: throw IllegalStateException("Redirect without Location header (HTTP $code)")
                    conn.disconnect()
                    currentUrl = location
                    redirects++
                } else {
                    break
                }
            }

            val activeConn = conn ?: throw IllegalStateException("Unable to open APK download connection.")
            if (activeConn.responseCode !in 200..299) {
                throw IllegalStateException("APK download failed with HTTP ${activeConn.responseCode}")
            }

            val headerLen = activeConn.contentLengthLong
            val totalBytes = if (headerLen > 0L) headerLen else release.fileSizeBytes
            val digest = MessageDigest.getInstance("SHA-256")
            var downloaded = 0L

            activeConn.inputStream.use { input ->
                FileOutputStream(targetFile).use { output ->
                    val buffer = ByteArray(16 * 1024)
                    while (true) {
                        val read = input.read(buffer)
                        if (read <= 0) break
                        output.write(buffer, 0, read)
                        digest.update(buffer, 0, read)
                        downloaded += read
                        val frac = if (totalBytes > 0L) {
                            (downloaded.toFloat() / totalBytes.toFloat()).coerceIn(0f, 1f)
                        } else 0f
                        onProgress(frac, downloaded, totalBytes)
                    }
                    output.flush()
                }
            }

            // Enforce SHA-256 checksum integrity when manifest supplies a digest
            if (release.sha256.isNotBlank()) {
                val actualSha256 = digest.digest().joinToString("") { "%02x".format(it) }
                if (!actualSha256.equals(release.sha256.trim(), ignoreCase = true)) {
                    targetFile.delete()
                    throw SecurityException(
                        "APK SHA-256 integrity check failed. Expected ${release.sha256.take(12)}..., got ${actualSha256.take(12)}..."
                    )
                }
            }

            onProgress(1f, downloaded, if (totalBytes > 0L) totalBytes else downloaded)
            targetFile
        } finally {
            conn?.disconnect()
        }
    }

    fun canInstallPackagesInApp(context: Context): Boolean {
        return if (Build.VERSION.SDK_INT >= Build.VERSION_CODES.O) {
            context.packageManager.canRequestPackageInstalls()
        } else {
            true
        }
    }

    fun buildInstallPermissionIntent(context: Context): Intent {
        return Intent(
            Settings.ACTION_MANAGE_UNKNOWN_APP_SOURCES,
            Uri.parse("package:${context.packageName}")
        )
    }

    fun buildInAppInstallIntent(context: Context, apkFile: File): Intent {
        val apkUri = FileProvider.getUriForFile(
            context,
            "${context.packageName}.fileprovider",
            apkFile
        )
        return Intent(Intent.ACTION_VIEW).apply {
            setDataAndType(apkUri, "application/vnd.android.package-archive")
            addFlags(Intent.FLAG_GRANT_READ_URI_PERMISSION)
            addFlags(Intent.FLAG_ACTIVITY_NEW_TASK)
        }
    }

    internal fun parseManifestJson(rawJson: String): AppReleaseInfo? {
        return runCatching {
            val obj = JSONObject(rawJson)
            val versionCode = obj.optInt("versionCode", 0)
            val versionName = obj.optString("versionName", "").trim()
            val apkUrl = obj.optString("apkUrl", "").trim()
            if (apkUrl.isBlank() || (versionCode <= 0 && versionName.isBlank())) return null
            AppReleaseInfo(
                versionCode = versionCode,
                versionName = versionName.ifBlank { versionCode.toString() },
                apkFileName = obj.optString("apkFileName", "BSA-YourView-v$versionName.apk"),
                apkUrl = apkUrl,
                sha256 = obj.optString("sha256", "").trim(),
                fileSizeBytes = obj.optLong("fileSizeBytes", 0L),
                releaseNotes = obj.optString("releaseNotes", "").trim(),
                publishedAtUtc = obj.optString("publishedAtUtc", "").trim()
            )
        }.getOrNull()
    }

    internal fun parseGitHubReleaseApiJson(rawJson: String): AppReleaseInfo? {
        return runCatching {
            val obj = JSONObject(rawJson)
            val tag = obj.optString("tag_name", "").trim().lstripVersionPrefix()
            val body = obj.optString("body", "").trim()
            val publishedAt = obj.optString("published_at", "").trim()
            val assets = obj.optJSONArray("assets") ?: return null
            var apkAsset: JSONObject? = null
            for (i in 0 until assets.length()) {
                val a = assets.optJSONObject(i) ?: continue
                if (a.optString("name", "").endsWith(".apk", ignoreCase = true)) {
                    apkAsset = a
                    break
                }
            }
            val asset = apkAsset ?: return null
            val apkUrl = asset.optString("browser_download_url", "").trim()
            if (apkUrl.isBlank()) return null

            // Derive numeric build code from final semver segment if present (e.g. 1.0.5 -> 5)
            val derivedCode = tag.split(".").lastOrNull()?.toIntOrNull() ?: 0
            AppReleaseInfo(
                versionCode = derivedCode,
                versionName = tag.ifBlank { "latest" },
                apkFileName = asset.optString("name", "BSA-YourView.apk"),
                apkUrl = apkUrl,
                sha256 = "",
                fileSizeBytes = asset.optLong("size", 0L),
                releaseNotes = body.ifBlank { "New BSA-YourView release v$tag available." },
                publishedAtUtc = publishedAt
            )
        }.getOrNull()
    }

    internal fun isNewerVersion(
        remoteCode: Int,
        remoteName: String,
        localCode: Int,
        localName: String
    ): Boolean {
        if (remoteCode > 0 && localCode > 0 && remoteCode != localCode) {
            return remoteCode > localCode
        }
        val rParts = remoteName.lstripVersionPrefix().split(".").map { it.toIntOrNull() ?: 0 }
        val lParts = localName.lstripVersionPrefix().split(".").map { it.toIntOrNull() ?: 0 }
        val maxLen = maxOf(rParts.size, lParts.size)
        for (i in 0 until maxLen) {
            val r = rParts.getOrElse(i) { 0 }
            val l = lParts.getOrElse(i) { 0 }
            if (r != l) return r > l
        }
        return false
    }

    private fun String.lstripVersionPrefix(): String = trim().removePrefix("v").removePrefix("V")
}
